def render_entry(entry: dict) -> str:
    badges = [f"{flag(entry['country_or_body'])} `{entry['country_or_body']}`", f"`{entry['entry_type']}`"]
    if entry.get("hosting_note"):
        badges.append(f"`{entry['hosting_note']}`")
    if entry.get("license"):
        badges.append(f"`{entry['license']}`")
    if entry.get("confidence") == "medium":
        badges.append("⚠️")

    line = f"- [{entry['name']}]({entry['url']}) - {entry['description']} " + " ".join(badges)
    if entry.get("repo"):
        line += f" ([source]({entry['repo']}))"
    if entry.get("notes"):
        line += f"\n  <br><sub>{entry['notes']}</sub>"
    return line


def render_readme(categories, entries_by_slug, repo: str) -> str:
    total = sum(len(v) for v in entries_by_slug.values())
    # Count jurisdictions, not "Country/Agency" pairs, so the badge agrees with
    # the coverage table further down.
    bodies = {
        e["country_or_body"].split("/", 1)[0].strip()
        for v in entries_by_slug.values()
        for e in v
    }

    parts = [
        HEADER.format(repo=repo, count=total, countries=len(bodies)),
        GENERATED,
        "",
        LEGEND,
        "## Contents",
        "",
    ]

    for category in categories:
        heading = f"{category.emoji} {category.name}".strip()
        count = len(entries_by_slug[category.slug])
        parts.append(f"- [{heading}](#{anchor(heading)}) ({count})")
        for sub in subcategory_order(category, entries_by_slug[category.slug]):
            n = sum(1 for e in entries_by_slug[category.slug] if e["subcategory"] == sub)
            if n:
                parts.append(f"  - [{sub}](#{anchor(sub)}) ({n})")
    parts += ["- [Coverage](#coverage)", "- [Contributing](#contributing)", ""]

    for category in categories:
        entries = entries_by_slug[category.slug]
        heading = f"{category.emoji} {category.name}".strip()
        parts += [f"## {heading}", "", category.description, ""]

        rendered_subs = set()
        for sub in subcategory_order(category, entries):
            items = sorted(
                (e for e in entries if e["subcategory"] == sub),
                key=lambda e: e["name"].lower(),
            )
            if not items:
                continue
            rendered_subs.add(sub)
            parts += [f"### {sub}", ""]
            parts += [render_entry(e) for e in items]
            parts.append("")

        orphans = sorted({e["subcategory"] for e in entries} - rendered_subs)
        if orphans:  # validate.py rejects these, but never silently drop data
            parts += [f"### {o}" for o in orphans]

    parts += [render_coverage(categories, entries_by_slug), FOOTER.format(repo=repo)]
    return "\n".join(parts).rstrip() + "\n"


def render_coverage(categories, entries_by_slug) -> str:
    all_entries = [e for v in entries_by_slug.values() for e in v]
    by_country = Counter(e["country_or_body"].split("/")[0] for e in all_entries)
    by_type = Counter(e["entry_type"] for e in all_entries)
    open_source = sum(1 for e in all_entries if "[Open Source]" in (e.get("hosting_note") or ""))

    rows = [
        "## Coverage",
        "",
        f"{len(all_entries)} verified entries spanning {len(by_country)} countries and EU bodies, "
        f"{open_source} of them open-source tooling. The uneven distribution is real: "
        "some sectors have a mature European toolchain, others have a regulation and "
        "not much else yet.",
        "",
        "| Category | Entries |",
        "| --- | ---: |",
    ]
    for category in categories:
        rows.append(f"| {category.name} | {len(entries_by_slug[category.slug])} |")

    rows += ["", "| Country or body | Entries |", "| --- | ---: |"]
    for country, n in by_country.most_common():
        rows.append(f"| {flag(country)} {country} | {n} |")

    rows += ["", "| Resource type | Entries |", "| --- | ---: |"]
    for kind, n in by_type.most_common():
        rows.append(f"| {kind} | {n} |")

    rows.append("")
    return "\n".join(rows)


