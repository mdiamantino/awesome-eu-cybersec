def _matches(entry: dict, tags: tuple[str, ...], phrases: tuple[str, ...]) -> bool:
    if set(entry.get("tags", [])) & set(tags):
        return True
    text = f"{entry['name']} {entry['description']}".lower()
    return any(phrase in text for phrase in phrases)


def render_by_regulation(categories, entries_by_slug) -> str:
    flat = [
        {"category": c.name, **e} for c in categories for e in entries_by_slug[c.slug]
    ]
    parts = [
        "# By regulation",
        "",
        GENERATED,
        "",
        "A cross-index of the same entries as [`README.md`](../README.md), grouped by the",
        "instrument that puts them in scope. An entry can appear under more than one",
        "heading, and an entry that appears under none is still in scope through its",
        "maintainer rather than through a specific regulation.",
        "",
    ]
    for title, citation, tags, phrases in REGULATIONS:
        hits = sorted(
            (e for e in flat if _matches(e, tags, phrases)), key=lambda e: e["name"].lower()
        )
        parts += [f"## {title}", "", f"*{citation}* - {len(hits)} entries", ""]
        for entry in hits:
            parts.append(
                f"- [{entry['name']}]({entry['url']}) - {entry['description']} "
                f"{flag(entry['country_or_body'])} `{entry['country_or_body']}` "
                f"<sub>{entry['category']}</sub>"
            )
        parts.append("")
    return "\n".join(parts).rstrip() + "\n"


def render_exports(categories, entries_by_slug) -> tuple[str, str]:
    flat = []
    for category in categories:
        for entry in entries_by_slug[category.slug]:
            flat.append({"category": category.name, **entry})

    yml = (
        "# GENERATED by scripts/build.py - do not edit.\n"
        "# Flat export of data/resources/*.yml for downstream consumers.\n"
        + yaml.safe_dump(flat, sort_keys=False, allow_unicode=True, width=100)
    )
    js = json.dumps(
        {"version": 1, "count": len(flat), "entries": flat}, indent=2, ensure_ascii=False
    ) + "\n"
    return yml, js


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    parser.add_argument("--repo", default="mdiamantino/awesome-eu-cybersec", help="owner/name for badges")
    args = parser.parse_args()

    categories, entries_by_slug = load_all()
    readme = render_readme(categories, entries_by_slug, args.repo)
    export_yml, export_json = render_exports(categories, entries_by_slug)

    targets: list[tuple[Path, str]] = [
        (README, readme),
        (BY_REGULATION, render_by_regulation(categories, entries_by_slug)),
        (EXPORT_YML, export_yml),
        (EXPORT_JSON, export_json),
    ]

    if args.check:
        stale = [p.name for p, content in targets if not p.exists() or p.read_text(encoding="utf-8") != content]
        if stale:
            print("stale generated files: " + ", ".join(stale))
            print("run: make build   (or: python3 scripts/build.py) and commit the result")
            return 1
        print("generated files are up to date")
        return 0

    for path, content in targets:
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
